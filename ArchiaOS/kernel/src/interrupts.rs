//! Minimal x86-64 exception IDT for early-kernel diagnostics (P2).
//!
//! All architectural exception vectors receive interrupt gates. Error-code
//! exceptions are normalized by their assembly stubs so the common dispatcher
//! always receives (vector, error_code). Handlers are fatal until recovery and
//! per-task exception delivery are designed.

use core::arch::{asm, global_asm};
use core::sync::atomic::{AtomicU64, Ordering};

const IDT_ENTRY_COUNT: usize = 256;
const INTERRUPT_GATE: u8 = 0x8e;

pub use crate::interrupt_vectors::{
    classify_interrupt_vector, cpu_exception_has_error_code, eoi_plan_for_handled_irq,
    legacy_pic_irq_for_vector, legacy_pic_vector_for_irq, split_x86_64_idt_handler_address,
    InterruptVectorClass,
    LEGACY_PIC_IRQ_COUNT,
    LEGACY_PIC_VECTOR_BASE,
};

#[repr(C, packed)]
#[derive(Clone, Copy)]
struct IdtEntry {
    offset_low: u16,
    selector: u16,
    ist: u8,
    attributes: u8,
    offset_middle: u16,
    offset_high: u32,
    reserved: u32,
}

impl IdtEntry {
    const MISSING: Self = Self {
        offset_low: 0,
        selector: 0,
        ist: 0,
        attributes: 0,
        offset_middle: 0,
        offset_high: 0,
        reserved: 0,
    };

    fn interrupt_gate(handler: u64, selector: u16) -> Self {
        let (offset_low, offset_middle, offset_high) =
            split_x86_64_idt_handler_address(handler);
        Self {
            offset_low,
            selector,
            ist: 0,
            attributes: INTERRUPT_GATE,
            offset_middle,
            offset_high,
            reserved: 0,
        }
    }
}

#[repr(C, packed)]
struct Idtr {
    limit: u16,
    base: u64,
}

// The x86-64 IDT gate is exactly 16 bytes; the IDTR operand is exactly
// 10 bytes (a 16-bit limit followed by a 64-bit base). Keep these checked at
// compile time so a future field or representation change cannot silently
// corrupt LIDT or the IDT indexing arithmetic.
const _: [(); 16] = [(); core::mem::size_of::<IdtEntry>()];
const _: [(); 10] = [(); core::mem::size_of::<Idtr>()];
const _: [(); IDT_ENTRY_COUNT] = [(); 256];

static mut IDT: [IdtEntry; IDT_ENTRY_COUNT] = [IdtEntry::MISSING; IDT_ENTRY_COUNT];

extern "C" {
    static isr_stub_table: [u64; IDT_ENTRY_COUNT];
    fn isr_test_return_stub();
    fn isr_spurious_return_stub();
}

const TEST_RETURN_VECTOR: usize = 0xF1;
const SPURIOUS_VECTOR: usize = 0xFF;
static TEST_INTERRUPT_COUNT: AtomicU64 = AtomicU64::new(0);
static SPURIOUS_INTERRUPT_COUNT: AtomicU64 = AtomicU64::new(0);

#[repr(C)]
struct TestInterruptFrame {
    r15: u64, r14: u64, r13: u64, r12: u64, r11: u64, r10: u64, r9: u64, r8: u64,
    rdi: u64, rsi: u64, rbp: u64, rbx: u64, rdx: u64, rcx: u64, rax: u64,
    vector: u64, error_code: u64, rip: u64, cs: u64, rflags: u64,
}

#[no_mangle]
extern "C" fn archiaos_test_interrupt_dispatch(frame: *mut TestInterruptFrame) -> *mut TestInterruptFrame {
    TEST_INTERRUPT_COUNT.fetch_add(1, Ordering::SeqCst);
    frame
}

#[no_mangle]
extern "C" fn archiaos_spurious_interrupt_dispatch(frame: *mut TestInterruptFrame) -> *mut TestInterruptFrame {
    SPURIOUS_INTERRUPT_COUNT.fetch_add(1, Ordering::SeqCst);
    frame
}

/// Exercise a real ring-0 software interrupt and its IRETQ return path.
/// This does not enable maskable interrupts or unmask any hardware IRQ.
pub fn return_path_self_test() -> bool {
    let before = TEST_INTERRUPT_COUNT.load(Ordering::SeqCst);
    let flags: u64;
    // SAFETY: this runs only after the kernel has installed vector 0xF1.
    // Save the caller's IF state and force IF=0 during the test so the return
    // path is not interrupted by unrelated maskable IRQs.
    unsafe {
        asm!("pushfq", "pop {flags}", "cli", flags = out(reg) flags);
        asm!("int 0xF1");
        if saved_interrupts_enabled(flags) {
            asm!("sti", options(nostack));
        }
    }
    TEST_INTERRUPT_COUNT.load(Ordering::SeqCst) == before.wrapping_add(1)
}

/// Verify that the returning software-interrupt gate preserves every
/// general-purpose register it promises to save. The handler must return the
/// original interrupt frame, and IRETQ must restore the interrupted state.
pub fn register_preservation_self_test() -> bool {
    let (mut rax, mut rcx, mut rdx, mut rbx) = (
        0x1122_3344_5566_7788u64,
        0x2233_4455_6677_8899u64,
        0x3344_5566_7788_99aau64,
        0x4455_6677_8899_aabbu64,
    );
    let (mut rbp, mut rsi, mut rdi, mut r8) = (
        0x5566_7788_99aa_bbccu64,
        0x6677_8899_aabb_ccddu64,
        0x7788_99aa_bbcc_ddeeu64,
        0x8899_aabb_ccdd_eeffu64,
    );
    let (mut r9, mut r10, mut r11, mut r12) = (
        0x99aa_bbcc_ddee_ff01u64,
        0xaabb_ccdd_eeff_0123u64,
        0xbbcc_ddee_ff01_2345u64,
        0xccdd_eeff_0123_4567u64,
    );
    let (mut r13, mut r14, mut r15) = (
        0xddee_ff01_2345_6789u64,
        0xeeff_0123_4567_89abu64,
        0xff01_2345_6789_abcdu64,
    );
    // SAFETY: vector 0xF1 is installed before this self-test and maskable
    // interrupts are disabled by the boot-time caller. Each operand is both
    // input and output so the compiler checks the actual register after IRETQ.
    unsafe {
        asm!(
            "int 0xF1",
            inout("rax") rax, inout("rcx") rcx, inout("rdx") rdx,
            inout("rbx") rbx, inout("rbp") rbp, inout("rsi") rsi,
            inout("rdi") rdi, inout("r8") r8, inout("r9") r9,
            inout("r10") r10, inout("r11") r11, inout("r12") r12,
            inout("r13") r13, inout("r14") r14, inout("r15") r15,
            options(nostack),
        );
    }
    (rax, rcx, rdx, rbx, rbp, rsi, rdi, r8, r9, r10, r11, r12, r13, r14, r15)
        == (
            0x1122_3344_5566_7788, 0x2233_4455_6677_8899,
            0x3344_5566_7788_99aa, 0x4455_6677_8899_aabb,
            0x5566_7788_99aa_bbcc, 0x6677_8899_aabb_ccdd,
            0x7788_99aa_bbcc_ddee, 0x8899_aabb_ccdd_eeff,
            0x99aa_bbcc_ddee_ff01, 0xaabb_ccdd_eeff_0123,
            0xbbcc_ddee_ff01_2345, 0xccdd_eeff_0123_4567,
            0xddee_ff01_2345_6789, 0xeeff_0123_4567_89ab,
            0xff01_2345_6789_abcd,
        )
}

/// Exercise the dedicated spurious-vector gate. A local-APIC spurious interrupt
/// returns without EOI, so this path only records the event.
pub fn spurious_return_path_self_test() -> bool {
    let before = SPURIOUS_INTERRUPT_COUNT.load(Ordering::SeqCst);
    let flags: u64;
    // SAFETY: install() installs the dedicated 0xFF gate before this test runs.
    unsafe {
        asm!("pushfq", "pop {flags}", "cli", flags = out(reg) flags);
        asm!("int 0xFF");
        if saved_interrupts_enabled(flags) {
            asm!("sti", options(nostack));
        }
    }
    SPURIOUS_INTERRUPT_COUNT.load(Ordering::SeqCst) == before.wrapping_add(1)
}

#[inline]
const fn saved_interrupts_enabled(rflags: u64) -> bool {
    rflags & (1 << 9) != 0
}

/// Install all 256 IDT entries with vector-specific stubs.
/// Every vector reports its actual number to the fatal dispatcher until safe
/// IRQ dispatch and return paths are implemented. Interrupts remain disabled.
pub unsafe fn install() {
    let selector: u16;
    // SAFETY: reading CS is an architectural, side-effect-free operation.
    unsafe { asm!("mov {0:x}, cs", out(reg) selector, options(nomem, nostack, preserves_flags)) };

    for vector in 0..IDT_ENTRY_COUNT {
        // SAFETY: the vector is bounded by IDT_ENTRY_COUNT and the complete
        // stub table is linked into the kernel image.
        let handler = unsafe { core::ptr::addr_of!(isr_stub_table).cast::<u64>().add(vector).read() };
        let entry = IdtEntry::interrupt_gate(handler, selector);
        // SAFETY: bounded index; IDT is initialized before it is loaded.
        unsafe { core::ptr::addr_of_mut!(IDT).cast::<IdtEntry>().add(vector).write(entry) };
    }

    // Override one otherwise-fatal vector with a dedicated, fully saved
    // software-interrupt return stub. Hardware IRQ vectors remain fatal/masked.
    let test_gate = IdtEntry::interrupt_gate(isr_test_return_stub as usize as u64, selector);
    unsafe { core::ptr::addr_of_mut!(IDT).cast::<IdtEntry>().add(TEST_RETURN_VECTOR).write(test_gate) };

    // The APIC spurious vector is special: return directly and do not send EOI.
    let spurious_gate = IdtEntry::interrupt_gate(isr_spurious_return_stub as usize as u64, selector);
    unsafe { core::ptr::addr_of_mut!(IDT).cast::<IdtEntry>().add(SPURIOUS_VECTOR).write(spurious_gate) };

    let descriptor = Idtr {
        limit: (core::mem::size_of::<IdtEntry>() * IDT_ENTRY_COUNT - 1) as u16,
        base: core::ptr::addr_of!(IDT) as u64,
    };
    // SAFETY: IDT and descriptor remain valid for the kernel lifetime; the descriptor
    // covers all 256 initialized gates (exceptions plus fatal defaults).
    unsafe { asm!("lidt [{0}]", in(reg) &descriptor, options(readonly, nostack, preserves_flags)) };
}

